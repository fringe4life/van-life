import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import subsetFont from "subset-font";
import { MONEY_GLYPHS, MONEY_UNICODE_RANGE } from "../app/fonts/money-glyphs";

/**
 * Builds the committed Space Mono money face (#408).
 *
 * Space Mono is only ever used for displayed currency, so the shipped woff2s do
 * not need the full latin set. Both weights are subset to `MONEY_GLYPHS` and
 * declared with a matching `unicode-range`, which keeps the download to the
 * characters a price can actually contain and guarantees the file never blocks
 * text that is not money.
 *
 * Output is committed: `bun run build` never generates fonts, so a clean tree
 * has to build without running this script.
 */
const SOURCE_DIR = path.resolve("node_modules/@fontsource/space-mono/files");
const OUTPUT_DIR = path.resolve("app/fonts/money");
const WEIGHTS = [400, 700] as const;
const FAMILY = "Space Mono";

const CSS_HEADER =
  "/* Generated by `bun run fonts:subset-money`. Do not edit by hand. */";

/**
 * Space Mono ships 400 and 700 only. Anything heavier in a money style resolves
 * down to 700 rather than synthesising a new weight.
 */
const toFontFace = (
  weight: number
): string => `/* space-mono-latin-${weight}-normal (money glyphs) */
@font-face {
  font-display: swap;
  font-family: "${FAMILY}";
  font-style: normal;
  font-weight: ${weight};
  src: url("./space-mono-${weight}.woff2") format("woff2");
  unicode-range: ${MONEY_UNICODE_RANGE};
}`;

interface SubsetFace {
  css: string;
  measurement: string;
}

const buildFace = async (weight: number): Promise<SubsetFace> => {
  const source = await readFile(
    path.join(SOURCE_DIR, `space-mono-latin-${weight}-normal.woff2`)
  );
  const subset = await subsetFont(source, MONEY_GLYPHS, {
    targetFormat: "woff2",
  });

  await writeFile(path.join(OUTPUT_DIR, `space-mono-${weight}.woff2`), subset);

  const saved = Math.round((1 - subset.length / source.length) * 100);
  return {
    css: toFontFace(weight),
    measurement: `  ${weight}: ${source.length} B → ${subset.length} B (−${saved}%)`,
  };
};

const build = async (): Promise<void> => {
  await mkdir(OUTPUT_DIR, { recursive: true });

  // `Promise.all` keeps the weights in declaration order, so regenerating a
  // clean tree produces no diff.
  const faces = await Promise.all(WEIGHTS.map((weight) => buildFace(weight)));

  await writeFile(
    path.join(OUTPUT_DIR, "money.css"),
    `${CSS_HEADER}\n\n${faces.map((face) => face.css).join("\n\n")}\n`,
    "utf8"
  );

  console.log("Space Mono money subset written to app/fonts/money");
  console.log(faces.map((face) => face.measurement).join("\n"));
  console.log(`  glyphs: ${MONEY_GLYPHS.length}`);
  console.log(`  range:  ${MONEY_UNICODE_RANGE}`);
};

await build();
